import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { PROMPT_HASH, FAQ_HASH } from "./knowledgeBundle.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "../../..");

const promptPath = path.join(repoRoot, "documents/06-security-ai/assistant-system-prompt.md");
const faqPath = path.join(repoRoot, "documents/06-security-ai/assistant-help-faq.md");
const outputPath = path.join(repoRoot, "backend/src/assistant/knowledgeBundle.ts");

export function extractSystemPrompt(raw: string): { prompt: string; version: string; hash: string } {
  const versionMatch = /Phiên bản:\s*\*\*([^*]+)\*\*/.exec(raw);
  const version = versionMatch ? versionMatch[1].trim() : "help-prompt-v0.4";

  const blockMatch = /~~~text\r?\n([\s\S]*?)\r?\n~~~/m.exec(raw);
  if (!blockMatch) {
    throw new Error("Could not find ~~~text block in assistant-system-prompt.md");
  }

  const prompt = blockMatch[1].trim();
  if (!prompt) {
    throw new Error("Extracted system prompt is empty");
  }

  const hash = crypto.createHash("sha256").update(prompt, "utf8").digest("hex");
  return { prompt, version, hash };
}

export function extractFaqPartA(raw: string): { partA: string; version: string; hash: string; itemIds: string[] } {
  const versionMatch = /Phiên bản:\s*([^\s—]+)/.exec(raw);
  const version = versionMatch ? versionMatch[1].trim() : "help-faq-v0.2";

  const partAStart = raw.indexOf("## Phần A — Bộ tri thức chuẩn hóa dành cho ngữ cảnh AI");
  if (partAStart === -1) {
    throw new Error("Could not find start of Phần A in assistant-help-faq.md");
  }

  const partBStart = raw.indexOf("## Phần B —", partAStart);
  if (partBStart === -1) {
    throw new Error("Could not find start of Phần B in assistant-help-faq.md");
  }

  const partA = raw.slice(partAStart, partBStart).trim();

  const idRegex = /###\s+(FAQ-\d{2})/g;
  const itemIds: string[] = [];
  let match: RegExpExecArray | null;
  while ((match = idRegex.exec(partA)) !== null) {
    itemIds.push(match[1]);
  }

  if (itemIds.length !== 20) {
    throw new Error(`Expected exactly 20 FAQ items in Phần A, found ${itemIds.length}: ${itemIds.join(", ")}`);
  }

  const uniqueIds = new Set(itemIds);
  if (uniqueIds.size !== 20) {
    throw new Error(`Duplicate FAQ IDs detected in Phần A: ${itemIds.join(", ")}`);
  }

  for (let i = 1; i <= 20; i++) {
    const expectedId = `FAQ-${String(i).padStart(2, "0")}`;
    if (!uniqueIds.has(expectedId)) {
      throw new Error(`Missing expected FAQ ID: ${expectedId}`);
    }
  }

  if (partA.includes("## Phần B") || partA.includes("## Phần C") || partA.includes("## Phần D")) {
    throw new Error("Phần A contains forbidden sections (Phần B/C/D)");
  }

  const hash = crypto.createHash("sha256").update(partA, "utf8").digest("hex");
  return { partA, version, hash, itemIds };
}

export function generateBundleContent(): string {
  const promptRaw = fs.readFileSync(promptPath, "utf8");
  const faqRaw = fs.readFileSync(faqPath, "utf8");

  const promptInfo = extractSystemPrompt(promptRaw);
  const faqInfo = extractFaqPartA(faqRaw);

  return `// Code generated by backend/scripts/bundle-assistant-knowledge.ts. DO NOT EDIT.
// Source: documents/06-security-ai/assistant-system-prompt.md & assistant-help-faq.md

export const PROMPT_VERSION = ${JSON.stringify(promptInfo.version)};
export const PROMPT_HASH = ${JSON.stringify(promptInfo.hash)};
export const SYSTEM_PROMPT = ${JSON.stringify(promptInfo.prompt)};

export const FAQ_VERSION = ${JSON.stringify(faqInfo.version)};
export const FAQ_HASH = ${JSON.stringify(faqInfo.hash)};
export const FAQ_PART_A = ${JSON.stringify(faqInfo.partA)};

export const FAQ_ITEM_IDS = ${JSON.stringify(faqInfo.itemIds)} as const;
`;
}

export function verifyBundleSynchronization(): {
  isSynchronized: boolean;
  promptHashMatch: boolean;
  faqHashMatch: boolean;
  sourcePromptHash: string;
  sourceFaqHash: string;
  bundlePromptHash: string;
  bundleFaqHash: string;
} {
  const promptRaw = fs.readFileSync(promptPath, "utf8");
  const faqRaw = fs.readFileSync(faqPath, "utf8");

  const promptInfo = extractSystemPrompt(promptRaw);
  const faqInfo = extractFaqPartA(faqRaw);

  const promptHashMatch = promptInfo.hash === PROMPT_HASH;
  const faqHashMatch = faqInfo.hash === FAQ_HASH;

  return {
    isSynchronized: promptHashMatch && faqHashMatch,
    promptHashMatch,
    faqHashMatch,
    sourcePromptHash: promptInfo.hash,
    sourceFaqHash: faqInfo.hash,
    bundlePromptHash: PROMPT_HASH,
    bundleFaqHash: FAQ_HASH,
  };
}
